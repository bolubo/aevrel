"""Readiness conformance against fixtures shared with the Go controller.

The same JSON fixtures drive `internal/control/readiness_conformance_test.go`,
so any semantic drift between the two implementations fails a test on one
side or the other.

Every fixture that carries resume-state evidence embeds the manifest that
the closure summary claims to describe. The summary is not trusted on its
own: it is regenerated by the production summarizer (`resume_state_summary`)
and the readiness verdict is then derived from the typed manifest, so the
fixture cannot drift from the manifest it pretends to summarise.
"""

from __future__ import annotations

import json
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from collections import Counter

import pytest

from aevrel.agent.server import resume_state_summary
from aevrel.local import CheckpointRecord, DrillOutcome, RankInventory, Reason
from aevrel.local.readiness import assess_readiness
from aevrel.state import ResumeReason, ResumeStateReport
from aevrel.state.resume_state import classify_resume_state

FIXTURES = Path(__file__).parents[1] / "fixtures" / "readiness" / "conformance"


def fixture_paths() -> list[Path]:
    return sorted(FIXTURES.glob("*.json"))


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def build_record(payload: dict) -> CheckpointRecord:
    ranks = tuple(
        RankInventory(rank=item["rank"], shards=(), bytes=item["bytes"])
        for item in payload["ranks"]
    )
    reasons = tuple(
        Reason(code=item["code"], detail=item["detail"])
        for item in payload.get("reasons", ())
    )
    return CheckpointRecord(
        checkpoint=payload["checkpoint"],
        namespace=payload["namespace"],
        job_uid=payload["job_uid"],
        version=payload["version"],
        step=payload.get("step"),
        provider=payload["provider"],
        format_version=payload["format_version"],
        metadata_digest=payload["metadata_digest"],
        ranks=ranks,
        observed_at=payload["observed_at"],
        latest_mtime=payload.get("latest_mtime"),
        complete=payload["complete"],
        reasons=reasons,
        created_at=payload.get("created_at"),
    )


def build_drill(payload: dict | None) -> DrillOutcome | None:
    if payload is None:
        return None
    return DrillOutcome(
        phase=payload["phase"],
        succeeded=payload["succeeded"],
        steps_ran=payload.get("steps_ran", 0),
        proof_ref=payload.get("proof_ref", ""),
        detail=payload.get("detail", ""),
        resume_state_digests=tuple(payload.get("resume_manifest_digests", ())),
    )


def build_resume_state(
    summary: dict | None,
    manifest: dict | None,
    description: str,
) -> ResumeStateReport | None:
    """Reconstruct the report from the typed manifest, never trusting the
    fixture's own `status` / `codes` / `manifestDigest` except to assert they
    agree with what the production classifier produces for the manifest.
    """
    if summary is None:
        return None
    if manifest is not None:
        report = classify_resume_state(manifest)
        assert report.status == summary["status"], (
            f"fixture claims closure {summary['status']!r} but the embedded "
            f"manifest classifies as {report.status!r}: {description}"
        )
        declared = list(summary.get("codes", ()))
        actual = [reason.code for reason in report.reasons]
        assert Counter(declared) == Counter(actual), (
            f"fixture declares reason codes {declared} but the manifest yields "
            f"{actual}: {description}"
        )
        declared_digest = summary.get("manifestDigest")
        if declared_digest:
            assert declared_digest == report.manifest_digest, (
                f"fixture's manifestDigest does not match the manifest's "
                f"canonical digest: {description}"
            )
        return report
    return ResumeStateReport(
        status=summary["status"],
        reasons=tuple(
            ResumeReason(code=code, detail=f"fixture {code}")
            for code in summary.get("codes", ())
        ),
        manifest=None,
        manifest_digest=summary.get("manifestDigest"),
    )


@pytest.mark.parametrize(
    "path", fixture_paths(), ids=lambda path: path.stem
)
def test_conformance_case(path: Path) -> None:
    payload = load(path)
    now = datetime.fromisoformat(payload["now"].replace("Z", "+00:00"))
    result = assess_readiness(
        build_record(payload["record"]),
        now=now,
        max_age_seconds=int(payload["maxAgeSeconds"]),
        target_world_size=payload.get("targetWorldSize"),
        drill=build_drill(payload.get("drill")),
        resume_state=build_resume_state(
            payload.get("resumeState"),
            payload.get("manifest"),
            payload.get("description", ""),
        ),
        require_state_complete=bool(payload["requireStateComplete"]),
    )
    expected = payload["expected"]
    assert result.status.value == expected["status"], payload["description"]
    assert result.complete is expected["complete"]
    assert result.fresh is expected["fresh"]
    assert result.loadable == expected["loadable"]
    assert result.movable == expected["movable"]
    assert result.state_complete == expected["stateComplete"]
    assert result.readiness_level == expected["readinessLevel"]
    assert [reason.code for reason in result.reasons] == expected["reasons"]
    assert result.observed_at == expected["observedAt"], payload["description"]
    assert result.estimated_rto_seconds == expected["estimatedRtoSeconds"]
    assert result.target_world_size == expected["targetWorldSize"]
    assert result.last_drill == expected["lastDrill"]
    assert result.last_drill_digest == expected["lastDrillDigest"]


@pytest.mark.parametrize("path", fixture_paths(), ids=lambda path: path.stem)
def test_observed_at_is_utc_and_instant_matched(path: Path) -> None:
    payload = load(path)
    now = datetime.fromisoformat(payload["now"].replace("Z", "+00:00"))
    result = assess_readiness(
        build_record(payload["record"]),
        now=now,
        max_age_seconds=int(payload["maxAgeSeconds"]),
    )
    assert result.observed_at == payload["expected"]["observedAt"]
    assert result.observed_at.endswith("Z")
    parsed = datetime.fromisoformat(result.observed_at)
    assert parsed.utcoffset() == timedelta(0)
    assert parsed == now.astimezone(timezone.utc)


@pytest.mark.parametrize("path", fixture_paths(), ids=lambda path: path.stem)
def test_fixture_summary_is_the_production_summary(path: Path) -> None:
    """The closure summary a fixture declares must equal the one the agent
    would emit for the fixture's embedded manifest. The agent emits the v2
    wire shape (`closure`/`reasonCodes`/`components`/`manifestDigest`); the
    harness consumes the controller-internal shape
    (`status`/`closed`/`codes`/`manifestDigest`). Projecting the wire output
    onto the internal four fields must reproduce the fixture exactly, so a
    hand-written summary that drifted from the manifest fails here."""
    payload = load(path)
    manifest = payload.get("manifest")
    if manifest is None:
        pytest.skip("fixture has no resume-state evidence to summarise")
    with tempfile.TemporaryDirectory() as scratch:
        manifest_path = Path(scratch) / "resume-state.json"
        manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
        wire = resume_state_summary(manifest_path)
    projected = {
        "status": wire["closure"],
        "closed": wire["closure"] == "COMPLETE",
        "codes": list(wire["reasonCodes"]),
        "manifestDigest": wire["manifestDigest"] or "",
    }
    assert projected == payload["resumeState"], payload["description"]


def test_fixtures_cover_the_required_matrix() -> None:
    names = {path.stem for path in fixture_paths()}
    assert len(names) >= 14
    for required in (
        "l3-ready",
        "l3-stale",
        "l3-closure-incomplete-no-gate",
        "l4-ready",
        "l4-closure-incomplete",
        "l4-unanchored-closure",
        "l4-anchor-mismatch",
        "observed-at-offset",
        "target-world-movable",
    ):
        assert required in names
    payload = load(FIXTURES / "l4-closure-incomplete.json")
    assert payload["expected"]["stateComplete"] is False
    assert payload["expected"]["status"] != "READY"

    movable = load(FIXTURES / "target-world-movable.json")
    assert movable["targetWorldSize"] > 1
    assert movable["expected"]["movable"] is True
    assert movable["expected"]["status"] == "READY"


def test_offsets_normalize_to_the_same_instant() -> None:
    utc = load(FIXTURES / "l3-ready.json")
    offset = load(FIXTURES / "observed-at-offset.json")
    assert utc["now"] != offset["now"]
    assert utc["expected"]["observedAt"] == offset["expected"]["observedAt"]
    assert "+" not in utc["expected"]["observedAt"]
    assert utc["expected"]["observedAt"].endswith("Z")
